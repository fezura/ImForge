std::string SyntheticIconHeader(int extra, const char* min_cp = "0xe005", const char* max_cp = "0xf8ff") {
    std::string h = "// Generated by https://github.com/juliettef/IconFontCppHeaders\n#pragma once\n\n";
    h += "#define FONT_ICON_FILE_NAME_FAS \"fa-solid-900.ttf\"\n\n";
    h += std::string("#define ICON_MIN_FA ") + min_cp + "\n";
    h += std::string("#define ICON_MAX_16_FA ") + max_cp + "\n";
    h += std::string("#define ICON_MAX_FA ") + max_cp + "\n";
    h += "#define ICON_FA_0 \"0\"\t// U+0030\n";
    h += "#define ICON_FA_PLAY \"\\xef\\x81\\x8b\"\t// U+f04b\n";
    h += "#define ICON_FA_CIRCLE_PLAY \"\\xef\\x85\\x84\"\t// U+f144\n";
    h += "#define ICON_FA_WAND_MAGIC_SPARKLES \"\\xee\\x8b\\x8a\"\t// U+e2ca\n";
    h += "#define ICON_FA_DOLLAR_SIGN \"$\"\t// U+0024\n";
    h += "#define ICON_FA_BROKEN \"\\n\"\n";
    for (int i = 0; i < extra; ++i) {
        char buf[128];
        unsigned cp = 0xf100u + (unsigned)i;
        std::snprintf(buf, sizeof(buf), "#define ICON_FA_EXTRA_%02d \"\\x%02x\\x%02x\\x%02x\"\t// U+%04x\n", i,
                      0xE0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3F), 0x80 | (cp & 0x3F), cp);
        h += buf;
    }
    return h;
}

