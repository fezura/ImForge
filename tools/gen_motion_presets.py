def is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v)


def is_int(v):
    return is_num(v) and float(v).is_integer()


def g(v):
    return "%.6g" % v


def parse_ease(text):
    """Returns (kind, named, (p0, p1, p2, p3)) or raises ValueError."""
    if not isinstance(text, str):
        raise ValueError("must be a string")
    if text in EASES:
        return ("Named", text, (0.0, 0.0, 0.0, 0.0))
    m = BEZIER_RE.fullmatch(text)
    if m:
        x1, y1, x2, y2 = (float(x) for x in m.groups())
        if not (0.0 <= x1 <= 1.0 and 0.0 <= x2 <= 1.0):
            raise ValueError("%r: cubic-bezier x values must be within 0..1" % text)
        if not (-5.0 <= y1 <= 5.0 and -5.0 <= y2 <= 5.0):
            raise ValueError("%r: cubic-bezier y values must be within -5..5" % text)
        return ("CubicBezier", "Linear", (x1, y1, x2, y2))
    m = STEPS_RE.fullmatch(text)
    if m:
        n = int(m.group(1))
        if not 1 <= n <= 100:
            raise ValueError("%r: steps needs 1..100" % text)
        return ("Steps", "Linear", (float(n), 0.0, 0.0, 0.0))
    m = SPRING_RE.fullmatch(text)
    if m:
        k, d = float(m.group(1)), float(m.group(2))
        if not 0.0 < k <= 10000.0:
            raise ValueError("%r: spring stiffness must be within (0, 10000]" % text)
        if not 0.0 < d <= 1000.0:
            raise ValueError("%r: spring damping must be within (0, 1000]" % text)
        return ("Spring", "Linear", (k, d, 0.0, 0.0))
    raise ValueError("unknown ease %r (%s)" % (text, EASE_HELP))


def parse_color(s):
    return tuple(int(s[1 + i * 2:3 + i * 2], 16) / 255.0 for i in range(4))


def same(a, b):
    return all(abs(x - y) <= EPS for x, y in zip(a, b))


def identity(prop):
    ident = PROPS[prop][4]
    return (ident, ident, ident, ident) if prop == TINT else (ident, 0.0, 0.0, 0.0)


def check_track(key, track, default_ease, errs):
    prop = PROP_INDEX[key]
    lo, hi = PROPS[prop][2], PROPS[prop][3]
    if not isinstance(track, list):
        errs.append("tracks.%s must be an array of keyframes" % key)
        return None
    if len(track) < 2:
        errs.append("tracks.%s needs at least 2 keyframes (t = 0 and t = 1)" % key)
        return None
    if len(track) > MAX_KEYS:
        errs.append("tracks.%s has %d keyframes, the limit is %d" % (key, len(track), MAX_KEYS))
        return None
    n_errs = len(errs)
    keys, prev_t = [], None
    for i, kf in enumerate(track):
        where = "tracks.%s[%d]" % (key, i)
        if not isinstance(kf, dict):
            errs.append("%s must be an object {t, v, ease}" % where)
            continue
        for k in sorted(kf):
            if k not in ("t", "v", "ease"):
                errs.append("%s: unknown key %r" % (where, k))
        t = kf.get("t")
        if not is_num(t) or not 0.0 <= t <= 1.0:
            errs.append("%s: t must be a number within 0..1" % where)
            t = None
        elif prev_t is not None and t <= prev_t:
            errs.append("%s: t must increase (%s after %s)" % (where, g(t), g(prev_t)))
        if t is not None:
            prev_t = t
        v = kf.get("v")
        if prop == TINT:
            if not isinstance(v, str) or not COLOR_RE.fullmatch(v):
                errs.append("%s: tint values must be \"#rrggbbaa\" strings" % where)
                v = None
            else:
                v = parse_color(v)
        elif not is_num(v):
            errs.append("%s: v must be a number" % where)
            v = None
        elif not lo <= v <= hi:
            errs.append("%s: %s %s is outside %s..%s" % (where, key, g(v), g(lo), g(hi)))
            v = None
        else:
            v = (float(v), 0.0, 0.0, 0.0)
        ease = default_ease
        if "ease" in kf:
            try:
                ease = parse_ease(kf["ease"])
            except ValueError as e:
                errs.append("%s: ease %s" % (where, e))
        keys.append((t, v, ease))
    if len(errs) != n_errs:
        return None
    if keys[0][0] != 0.0:
        errs.append("tracks.%s: the first keyframe must have t = 0" % key)
    if keys[-1][0] != 1.0:
        errs.append("tracks.%s: the last keyframe must have t = 1" % key)
    return None if len(errs) != n_errs else (prop, keys)


def end_uses_last(direction, iterations):
    last = iterations - 1
    if direction == "normal":
        return True
    if direction == "reverse":
        return False
    if direction == "alternate":
        return last % 2 == 0
    return last % 2 == 1


def same_value(prop, a, b):
    if prop == ROTATE:
        turns = (b[0] - a[0]) / 360.0
        return abs(turns - round(turns)) * 360.0 <= EPS
    return same(a, b)


def check_identity(anim, errs):
    # rotate counts in full turns: 360 looks the same as 0
    cat, direction, iterations = anim["category"], anim["direction"], anim["iterations"]
    if cat in ("entrance", "exit") and iterations == 0:
        errs.append("%s animations can't repeat forever (iterations = 0)" % cat)
        return
    for prop, keys in anim["tracks"]:
        key, ident = PROPS[prop][0], identity(prop)
        start = keys[0][1] if direction in ("normal", "alternate") else keys[-1][1]
        if cat in START_IDENTITY and not same_value(prop, ident, start):
            errs.append("%s animations must start at identity: tracks.%s starts at %s, expected %s"
                        % (cat, key, fmt_value(prop, start), fmt_value(prop, ident)))
            continue
        if cat in END_IDENTITY and iterations > 0:
            end = keys[-1][1] if end_uses_last(direction, iterations) else keys[0][1]
            if not same_value(prop, ident, end):
                errs.append("%s animations must end at identity: tracks.%s ends at %s, expected %s"
                            % (cat, key, fmt_value(prop, end), fmt_value(prop, ident)))
                continue
        if cat == "loop" and direction in ("normal", "reverse"):
            if not same_value(prop, keys[0][1], keys[-1][1]):
                errs.append("loops must end where they start: tracks.%s starts at %s and ends at %s"
                            % (key, fmt_value(prop, keys[0][1]), fmt_value(prop, keys[-1][1])))


def fmt_value(prop, v):
    if prop == TINT:
        return "#" + "".join("%02x" % int(round(c * 255.0)) for c in v)
    return g(v[0])


def check_animation(obj, set_category=None, standalone=False):
    """Validates one AnimJson. Returns (anim, errors); anim is None when there are errors."""
    if not isinstance(obj, dict):
        return None, ["animation must be an object"]
    errs = []
    allowed = ANIM_KEYS | FILE_KEYS if standalone else ANIM_KEYS
    for k in sorted(obj):
        if k not in allowed:
            errs.append("unknown key %r" % k)
    if standalone:
        if "schemaVersion" in obj and obj["schemaVersion"] != 1:
            errs.append("schemaVersion must be 1")
        if "kind" in obj and obj["kind"] != "animation":
            errs.append("kind must be \"animation\"")
    name = obj.get("name")
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        errs.append("name must be PascalCase (letters and digits, starting with A-Z), got %r" % (name,))
    elif len(name) > MAX_NAME:
        errs.append("name is longer than %d characters" % MAX_NAME)
    elif name in RESERVED:
        errs.append("name %r is reserved" % name)
    category = obj.get("category", set_category)
    if category is None:
        errs.append("category is missing")
    elif category not in CATEGORIES:
        errs.append("unknown category %r (expected one of %s)" % (category, ", ".join(CATEGORIES)))
    elif set_category is not None and category != set_category:
        errs.append("category %r does not match the set category %r" % (category, set_category))
    for key in ("description", "credit"):
        if key in obj and not isinstance(obj[key], str):
            errs.append("%s must be a string" % key)
    tags = obj.get("tags", [])
    if not isinstance(tags, list) or not all(isinstance(t, str) and t for t in tags):
        errs.append("tags must be an array of non-empty strings")
        tags = []
    elif len(set(tags)) != len(tags):
        errs.append("tags has duplicates")
    duration = obj.get("duration")
    if not is_num(duration) or not 0.0 < duration <= 60.0:
        errs.append("duration must be a number of seconds within (0, 60]")
    delay = obj.get("delay", 0)
    if not is_num(delay) or not 0.0 <= delay <= 60.0:
        errs.append("delay must be a number of seconds within 0..60")
    iterations = obj.get("iterations", 0 if category == "loop" else 1)
    if not is_int(iterations) or not 0 <= iterations <= 1000:
        errs.append("iterations must be an integer within 0..1000 (0 repeats forever)")
        iterations = 1
    iterations = int(iterations)
    enums = {}
    for key, table, default in (("direction", DIRECTIONS, "normal"), ("fill", FILLS, "both"),
                                ("revealDir", REVEAL_DIRS, "left"),
                                ("trigger", TRIGGERS, DEFAULT_TRIGGER.get(category, "enter"))):
        v = obj.get(key, default)
        if v not in table:
            errs.append("%s must be one of %s, got %r" % (key, ", ".join(table), v))
            v = default
        enums[key] = v
    origin = obj.get("origin", {"x": 0.5, "y": 0.5})
    if (not isinstance(origin, dict) or sorted(origin) != ["x", "y"]
            or not all(is_num(origin[k]) and -1.0 <= origin[k] <= 2.0 for k in ("x", "y"))):
        errs.append("origin must be {\"x\": n, \"y\": n} with fractions within -1..2")
        origin = {"x": 0.5, "y": 0.5}
    default_ease = LINEAR
    if "ease" in obj:
        try:
            default_ease = parse_ease(obj["ease"])
        except ValueError as e:
            errs.append("ease %s" % e)
    tracks = obj.get("tracks")
    out_tracks = []
    if not isinstance(tracks, dict) or not tracks:
        errs.append("tracks must be an object with at least one track")
    else:
        for key in sorted(tracks, key=lambda k: PROP_INDEX.get(k, -1)):
            if key not in PROP_INDEX:
                errs.append("unknown track %r (expected one of %s)" % (key, ", ".join(p[0] for p in PROPS)))
                continue
            tr = check_track(key, tracks[key], default_ease, errs)
            if tr:
                out_tracks.append(tr)
    if errs:
        return None, errs
    anim = {
        "name": name, "category": category, "description": obj.get("description", ""), "tags": tags,
        "credit": obj.get("credit", ""), "duration": float(duration), "delay": float(delay),
        "iterations": iterations, "direction": enums["direction"], "fill": enums["fill"],
        "origin": (float(origin["x"]), float(origin["y"])), "revealDir": enums["revealDir"],
        "trigger": enums["trigger"], "tracks": out_tracks,
    }
    check_identity(anim, errs)
    return (None, errs) if errs else (anim, [])


def check_set(obj, require_description=False):
    """Validates an animationSet. Returns (category, anims, errors) with errors prefixed by animation name."""
    if not isinstance(obj, dict):
        return None, [], ["top level must be an object"]
    errs = []
    for k in sorted(obj):
        if k not in SET_KEYS:
            errs.append("unknown key %r" % k)
    if obj.get("schemaVersion") != 1:
        errs.append("schemaVersion must be 1")
    if obj.get("kind") != "animationSet":
        errs.append("kind must be \"animationSet\"")
    category = obj.get("category")
    if category not in CATEGORIES:
        errs.append("category must be one of %s, got %r" % (", ".join(CATEGORIES), category))
        category = None
    items = obj.get("animations")
    if not isinstance(items, list):
        errs.append("animations must be an array")
        items = []
    anims, seen = [], set()
    for i, item in enumerate(items):
        label = item.get("name") if isinstance(item, dict) and isinstance(item.get("name"), str) else "animations[%d]" % i
        anim, aerrs = check_animation(item, category)
        if anim and require_description and not anim["description"].strip():
            aerrs = ["description is required for bundled presets"]
            anim = None
        errs.extend("%s: %s" % (label, e) for e in aerrs)
        if anim:
            if anim["name"] in seen:
                errs.append("%s: duplicate name in this set" % anim["name"])
            seen.add(anim["name"])
            anims.append(anim)
    return category, anims, errs


def check_file(obj):
    """Hook for tools/validate_json.py: errors for one animation or animationSet file."""
    kind = obj.get("kind") if isinstance(obj, dict) else None
    if kind == "animationSet":
        return check_set(obj)[2]
    anim, errs = check_animation(obj, standalone=True)
    label = obj.get("name") if isinstance(obj, dict) and isinstance(obj.get("name"), str) else "animation"
    return ["%s: %s" % (label, e) for e in errs]


def load_json(path):
    def pairs(items):
        d = {}
        for k, v in items:
            if k in d:
                raise ValueError("duplicate key %r" % k)
            d[k] = v
        return d

    def bad_constant(c):
        raise ValueError("%s is not valid JSON" % c)

    with open(path, "r", encoding="utf-8") as f:
        return json.load(f, object_pairs_hook=pairs, parse_constant=bad_constant)


def rel(path):
    try:
        return os.path.relpath(path, ROOT).replace("\\", "/")
    except ValueError:
        return path.replace("\\", "/")


def load_sets(src):
    errors, anims, owner = [], [], {}
    paths = sorted(glob.glob(os.path.join(src, "*.imanims.json")), key=lambda p: os.path.basename(p))
    for path in paths:
        r = rel(path)
        try:
            obj = load_json(path)
        except (OSError, ValueError) as e:
            errors.append("%s: cannot parse: %s" % (r, e))
            continue
        category, file_anims, errs = check_set(obj, require_description=True)
        stem = os.path.basename(path)[:-len(".imanims.json")]
        if category and stem != category:
            errs.append("file should be named %s.imanims.json to match its category" % category)
        errors.extend("%s: %s" % (r, e) for e in errs)
        for a in file_anims:
            if a["name"] in owner:
                errors.append("%s: %s: name is already used in %s" % (r, a["name"], owner[a["name"]]))
                continue
            owner[a["name"]] = r
            anims.append(a)
    anims.sort(key=lambda a: (CATEGORIES.index(a["category"]), a["name"]))
    return anims, len(paths), errors


def cf(x):
    s = "%.9g" % x
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def c_ease(e):
    kind, named, p = e
    if e == LINEAR:
        return "{}"
    return "{::imb::EaseKind::%s, ::imb::Ease::%s, {%s}}" % (kind, named, ", ".join(cf(x) for x in p))


def wrap_names(names, indent="//   ", width=100):
    lines, cur = [], ""
    for n in names:
        piece = n if not cur else ", " + n
        if cur and len(indent) + len(cur) + len(piece) > width:
            lines.append(indent + cur + ",")
            cur = n
        else:
            cur += piece
    if cur:
        lines.append(indent + cur)
    return lines


def credits_block(anims):
    out = []
    ported = [a["name"] for a in anims if "animate.css" in a["credit"].lower()]
    others = [a for a in anims if a["credit"].strip() and "animate.css" not in a["credit"].lower()]
    if ported:
        out.append("// These presets are ports of keyframes from animate.css 4.1.0")
        out.append("// (https://github.com/animate-css/animate.css), used under the MIT license:")
        out.extend(wrap_names(sorted(ported)))
        out.append("//")
        out.extend(("// " + line).rstrip() for line in MIT_NOTICE.split("\n"))
        out.append("")
    if others:
        out.append("// Other credits:")
        out.extend("//   %s: %s" % (a["name"], a["credit"].strip()) for a in sorted(others, key=lambda a: a["name"]))
        out.append("")
    return out


def emit_anim(a):
    out = ["inline const ::imb::AnimDef* %s() {" % a["name"]]
    for i, (prop, keys) in enumerate(a["tracks"]):
        out.append("    static const ::imb::Keyframe k%d[] = {" % i)
        for t, v, ease in keys:
            out.append("        {%s, {%s}, %s}," % (cf(t), ", ".join(cf(x) for x in v), c_ease(ease)))
        out.append("    };")
    out.append("    static const ::imb::Track tracks[] = {")
    for i, (prop, keys) in enumerate(a["tracks"]):
        out.append("        {::imb::Prop::%s, k%d, %d}," % (PROPS[prop][1], i, len(keys)))
    out.append("    };")
    out.append("    static const ::imb::AnimDef def = {")
    out.append("        \"%s\", \"%s\", %s, %s, %d," % (a["name"], a["category"], cf(a["duration"]), cf(a["delay"]),
                                                     a["iterations"]))
    out.append("        ::imb::Direction::%s, ::imb::Fill::%s, ::ImVec2(%s, %s)," % (
        DIRECTIONS[a["direction"]], FILLS[a["fill"]], cf(a["origin"][0]), cf(a["origin"][1])))
    out.append("        ::imb::RevealDir::%s, ::imb::Trigger::%s, tracks, %d};" % (
        REVEAL_DIRS[a["revealDir"]], TRIGGERS[a["trigger"]], len(a["tracks"])))
    out.append("    return &def;")
    out.append("}")
    out.append("")
    return out


def emit_header(anims):
    out = [BANNER, "// Source: presets/animations/*.imanims.json, %d animations." % len(anims), "#pragma once",
           "#include \"imb_motion.h\"", ""]
    out.extend(credits_block(anims))
    out.extend(["namespace imb {", "namespace presets {", ""])
    category = None
    for a in anims:
        if a["category"] != category:
            category = a["category"]
            out.append("// %s" % category)
            out.append("")
        out.extend(emit_anim(a))
    out.append("inline const char* const* Names(int& count) {")
    if anims:
        out.append("    static const char* const names[] = {")
        out.extend("        \"%s\"," % a["name"] for a in anims)
        out.append("    };")
        out.append("    count = static_cast<int>(sizeof(names) / sizeof(names[0]));")
        out.append("    return names;")
    else:
        out.append("    count = 0;")
        out.append("    return nullptr;")
    out.append("}")
    out.append("")
    out.append("inline void RegisterAll() {")
    out.extend("    ::imb::RegisterAnim(%s());" % a["name"] for a in anims)
    out.append("}")
    out.append("")
    out.append("namespace detail {")
    out.append("// the registry calls RegisterAll() on first use once this header is part of the program")
    out.append("struct HookInstaller {")
    out.append("    HookInstaller() { ::imb::detail::MotionPresetsHook() = &RegisterAll; }")
    out.append("};")
    out.append("// static, not inline, so it builds as C++14. each TU stores the same pointer")
    out.append("static HookInstaller hook_installer;")
    out.append("}  // namespace detail")
    out.append("")
    out.append("}  // namespace presets")
    out.append("}  // namespace imb")
    return "\n".join(out) + "\n"


def main(argv):
    check = "--check" in argv
    src, out = DEFAULT_SRC, DEFAULT_OUT
    args = [a for a in argv if a != "--check"]
    i = 0
    while i < len(args):
        if args[i] in ("--src", "--out") and i + 1 < len(args):
            if args[i] == "--src":
                src = os.path.abspath(args[i + 1])
            else:
                out = os.path.abspath(args[i + 1])
            i += 2
        else:
            print(__doc__.strip())
            return 2
    anims, n_sets, errors = load_sets(src)
    if errors:
        for e in errors:
            print("ERROR " + e)
        print("gen_motion_presets: %d errors" % len(errors))
        return 1
    text = emit_header(anims)
    try:
        with open(out, "r", encoding="utf-8", newline="") as f:
            current = f.read()
    except OSError:
        current = None
    if check:
        if current != text:
            print("gen_motion_presets: %s is stale, run python tools/gen_motion_presets.py" % rel(out))
            return 1
        print("gen_motion_presets: %s is up to date (%d animations from %d sets)" % (rel(out), len(anims), n_sets))
        return 0
    if current != text:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("gen_motion_presets: wrote %s (%d animations from %d sets)" % (rel(out), len(anims), n_sets))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
