#!/usr/bin/env python3
"""Compile tools/fx/vulkan_shaders/*.{vert,frag} to SPIR-V and regenerate the C++ headers.
glslang is looked up via --glslang, $IMFORGE_GLSLANG, $VULKAN_SDK/bin, then PATH. The standalone
binary from https://github.com/KhronosGroup/glslang/releases is enough.
"""
import argparse
import os
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC_DIR = os.path.join(ROOT, "tools", "fx", "vulkan_shaders")

TARGETS = [
    {
        "out": os.path.join(ROOT, "include", "imforge", "fx", "imb_fx_vulkan_shaders.h"),
        "namespace": ["imb", "fx", "vk_shaders"],
        "shaders": [
            ("fullscreen.vert", "kFullscreenVertSpv"),
            ("blur.frag", "kBlurFragSpv"),
            ("composite.vert", "kCompositeVertSpv"),
            ("composite.frag", "kCompositeFragSpv"),
        ],
    },
    {
        "out": os.path.join(ROOT, "examples", "fx", "vulkan_sdl3_blur_demo", "demo_shaders.h"),
        "namespace": ["demo_shaders"],
        "shaders": [
            ("bg_quad.vert", "kBgQuadVertSpv"),
            ("bg_quad.frag", "kBgQuadFragSpv"),
        ],
    },
]


def find_glslang(explicit):
    candidates = []
    if explicit:
        candidates.append(explicit)
    if os.environ.get("IMFORGE_GLSLANG"):
        candidates.append(os.environ["IMFORGE_GLSLANG"])
    sdk = os.environ.get("VULKAN_SDK")
    exe = ".exe" if os.name == "nt" else ""
    if sdk:
        for name in ("glslang", "glslangValidator"):
            candidates.append(os.path.join(sdk, "bin", name + exe))
    for name in ("glslang", "glslangValidator"):
        found = shutil.which(name)
        if found:
            candidates.append(found)
    for c in candidates:
        if c and os.path.isfile(c):
            return c
    return None


def compile_spirv(glslang, src_path):
    fd, out_path = tempfile.mkstemp(suffix=".spv")
    os.close(fd)
    try:
        cmd = [glslang, "-V", "--target-env", "vulkan1.0", "-o", out_path, src_path]
        proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        if proc.returncode != 0:
            sys.stderr.write(proc.stdout)
            raise SystemExit("glslang failed on %s" % src_path)
        with open(out_path, "rb") as f:
            data = f.read()
    finally:
        try:
            os.remove(out_path)
        except OSError:
            pass
    if len(data) % 4 != 0 or len(data) < 20:
        raise SystemExit("bad SPIR-V size for %s" % src_path)
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    if words[0] != 0x07230203:
        raise SystemExit("bad SPIR-V magic for %s" % src_path)
    return words


def glslang_version(glslang):
    proc = subprocess.run([glslang, "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    first = proc.stdout.strip().splitlines()
    return first[0].strip() if first else "unknown"


def emit_header(target, glslang, version):
    lines = []
    lines.append("#pragma once")
    lines.append("// Generated by tools/fx/compile_vulkan_shaders.py from tools/fx/vulkan_shaders/. Do not edit.")
    lines.append("// Compiler: %s (glslang -V --target-env vulkan1.0)" % version)
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    lines.append("")
    for ns in target["namespace"]:
        lines.append("namespace %s {" % ns)
    lines.append("")
    for src_name, sym in target["shaders"]:
        src_path = os.path.join(SRC_DIR, src_name)
        with open(src_path, "r", encoding="utf-8") as f:
            source = f.read().rstrip("\n").split("\n")
        words = compile_spirv(glslang, src_path)
        lines.append("// --- %s ---" % src_name)
        for s in source:
            lines.append("// " + s if s else "//")
        lines.append("inline const uint32_t %s[] = {" % sym)
        per_line = 8
        for i in range(0, len(words), per_line):
            chunk = words[i:i + per_line]
            lines.append("    " + ", ".join("0x%08x" % w for w in chunk) + ",")
        lines.append("};")
        lines.append("inline const size_t %sSize = sizeof(%s);" % (sym[:-3], sym))
        lines.append("")
    for ns in reversed(target["namespace"]):
        lines.append("}  // namespace %s" % ns)
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glslang", default=None)
    args = ap.parse_args()
    glslang = find_glslang(args.glslang)
    if not glslang:
        raise SystemExit("glslang not found; pass --glslang or set VULKAN_SDK / IMFORGE_GLSLANG")
    version = glslang_version(glslang)
    for target in TARGETS:
        text = emit_header(target, glslang, version)
        os.makedirs(os.path.dirname(target["out"]), exist_ok=True)
        with open(target["out"], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(target["out"], ROOT))


if __name__ == "__main__":
    main()
